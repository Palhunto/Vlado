const {chromium} = require('playwright');
const {irParaGerenciar} = require('./qa_navegacao.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const [origin, output, chrome] = process.argv.slice(2);
(async () => {
  await fs.mkdir(output, {recursive:true});
  const browser = await chromium.launch({headless:true, ...(chrome ? {executablePath:chrome} : {})});
  const page = await browser.newPage({viewport:{width:1365, height:1000}});
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const trash = title => page.locator('#gerenciar-lixeira li').filter({has:page.getByRole('heading', {name:title, exact:true})});
  async function choose(id) {
    await page.selectOption('#gerenciar-caso', id);
    await page.locator('#gerenciar-selecao:not([hidden])').waitFor();
    await page.locator('#gerenciar-nome').filter({hasText:'Caso sintético ' + id}).waitFor();
  }
  async function confirm() {
    await page.locator('#excluir-dialogo[open]').waitFor();
    await page.click('#excluir-dialogo button[value="excluir"]');
    await page.locator('#excluir-dialogo').waitFor({state:'hidden'});
  }
  try {
    await page.goto(origin);
    await irParaGerenciar(page);
    await page.locator('#gerenciar-caso option[value="alpha"]').waitFor({state:'attached'});
    assert.equal(await page.locator('#selecao-acervo').isVisible(), false);
    assert.equal(await page.locator('#gerenciar-caso').inputValue(), '');
    await choose('alpha');
    assert.equal(await page.locator('#gerenciar-conversas button').count(), 1);
    assert.equal(await page.locator('#gerenciar-rodadas button').count(), 1);
    checks.push('Gerenciamento separado, sem seleção automática; rodadas vinculadas agrupadas na conversa.');
    await page.click('#gerenciar-excluir-caso');
    assert.equal(await page.locator('#excluir-dialogo button[value="cancelar"]').evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#gerenciar-caso').inputValue(), 'alpha');
    assert.match(await page.locator('#gerenciar-lixeira').innerText(), /vazia/);
    checks.push('Confirmação acessível, foco inicial em Cancelar e Escape sem exclusão.');
    await page.locator('#gerenciar-rodadas button').click();
    await confirm();
    await trash('Rodada 2').waitFor();
    assert.equal(await page.locator('#gerenciar-rodadas button').count(), 0);
    await trash('Rodada 2').getByRole('button').click();
    await page.locator('#gerenciar-rodadas button').waitFor();
    checks.push('Exclusão e restauração de rodada avulsa.');
    await page.click('#ver-codex');
    await page.locator('#codex-caso option[value="alpha"]').waitFor({state:'attached'});
    await page.selectOption('#codex-caso', 'alpha');
    await page.locator('#codex-conversa option[value="' + 'a'.repeat(32) + '"]').waitFor({state:'attached'});
    await page.selectOption('#codex-conversa', 'a'.repeat(32));
    await page.locator('#codex-status').filter({hasText:'Execução concluída'}).waitFor();
    await page.locator('#codex-acervo>summary').click();
    await page.locator('#codex-excluir:not([disabled])').waitFor();
    await page.click('#codex-excluir');
    await confirm();
    await page.locator('#codex-status').filter({hasText:'Conversa movida para a lixeira'}).waitFor();
    assert.equal(await page.locator('#codex-conversa').inputValue(), '');
    assert.equal(await page.locator('#codex-excluir').isDisabled(), true);
    await irParaGerenciar(page);
    await trash('Conversa · Pergunta sintética').waitFor();
    await page.locator('#gerenciar-conversas .manage-empty').waitFor();
    checks.push('Excluir conversa na tela de perguntas limpa a seleção e retira as rodadas vinculadas.');
    await page.click('#gerenciar-excluir-caso');
    await confirm();
    await trash('Apuração · Caso sintético alpha').waitFor();
    assert.equal(await trash('Conversa · Pergunta sintética').getByRole('button').isDisabled(), true);
    await page.reload();
    await irParaGerenciar(page);
    await trash('Apuração · Caso sintético alpha').waitFor();
    assert.equal(await page.locator('#gerenciar-caso option[value="alpha"]').count(), 0);
    await trash('Apuração · Caso sintético alpha').getByRole('button').click();
    await page.locator('#gerenciar-caso option[value="alpha"]').waitFor({state:'attached'});
    await choose('alpha');
    assert.equal(await page.locator('#gerenciar-conversas button').count(), 0);
    await trash('Conversa · Pergunta sintética').getByRole('button').click();
    await page.locator('#gerenciar-conversas button').waitFor();
    checks.push('Lixeira persiste na recarga; restaurar apuração respeita exclusão anterior da conversa.');
    await page.screenshot({path:path.join(output, 'gerenciar-desktop.png'), fullPage:true});
    await choose('beta');
    assert.equal(await page.locator('#gerenciar-excluir-caso').isDisabled(), true);
    assert.equal(await page.locator('#gerenciar-conversas button').isDisabled(), true);
    checks.push('Controles bloqueados durante execução sintética em andamento.');
    await choose('alpha');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path:path.join(output, 'gerenciar-mobile.png'), fullPage:true});
    await page.click('#gerenciar-excluir-caso');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path:path.join(output, 'confirmacao-mobile.png')});
    await page.keyboard.press('Escape');
    checks.push('Desktop e celular sem rolagem horizontal, inclusive na confirmação.');
    assert.deepEqual(errors, []);
    await fs.writeFile(path.join(output, 'resultado.json'), JSON.stringify({estado:'ok',checks,errors}, null, 2));
    process.stdout.write(JSON.stringify({estado:'ok', verificacoes:checks.length, errors}));
  } catch (error) {
    await page.screenshot({path:path.join(output, 'falha.png'), fullPage:true}).catch(() => {});
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
