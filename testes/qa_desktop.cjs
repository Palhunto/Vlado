const editor=require('./editor_notas.cjs');
'use strict';
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {PNG}=require('pngjs');
const pixelmatchModule=require('pixelmatch');
const pixelmatch=pixelmatchModule.default || pixelmatchModule;
const [origin,output,chat]=process.argv.slice(2);
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const result={checks:[],errors:[]};
  const requests=[];
  page.on('request',request=>{if(request.url().includes('/api/caderno-'))requests.push({url:request.url().split('/').pop(),data:request.postDataJSON()});});
  page.on('pageerror',error=>result.errors.push(error.message));
  const screenshot=async name=>page.screenshot({path:path.join(output,name+'.png')});
  const open=async id=>{const node=page.locator('#'+id);if(!await node.evaluate(el=>el.open))await node.locator(':scope > summary').click();};
  const findings=async()=>{
    await page.click('#ver-achados');
    await open('acervo-escolha');await page.selectOption('#rodada','R001');
    await open('achados-versoes');await page.selectOption('#achados-revisao','r2');await page.selectOption('#achados-geracao','g2');
    await page.locator('.finding-open').first().waitFor();
    await page.waitForFunction(()=>!$('achados-buscar').disabled);
  };
  try {
    await page.goto(origin);await page.locator('#area-inicio').waitFor({state:'visible'});
    await page.selectOption('#contexto-caso','alpha');
    assert.equal(await page.locator('#ver-achados').evaluate(el=>el.tagName),'A');
    assert.match(await page.locator('#ver-achados').getAttribute('href'),/area=achados.*caso=alpha/);
    const popupPromise=page.context().waitForEvent('page');
    await page.locator('#ver-achados').click({button:'middle'});
    const popup=await popupPromise;await popup.waitForLoadState();
    await popup.locator('#area-achados').waitFor({state:'visible'});await popup.close();
    assert.equal(await page.locator('#area-inicio').isVisible(),true);
    result.checks.push('Links desktop permitem abrir área em outra aba sem navegar a aba original.');
    await findings();
    assert.equal(await page.locator('#acervo-escolha').evaluate(el=>el.open),false);
    assert.equal(await page.locator('#achados-versoes').evaluate(el=>el.open),false);
    await page.evaluate(()=>scrollTo(0,0));await page.evaluate(()=>document.fonts.ready);
    const first=await page.locator('.finding-open').first().boundingBox();
    assert.ok(first.y<1000,'A primeira ficha precisa aparecer na primeira tela após selecionar a versão.');
    await screenshot('achados-desktop');
    await page.click('#achados-proximo');await page.waitForFunction(()=>$('achados-intervalo').textContent==='11–20 de 32');
    assert.equal(new URL(page.url()).searchParams.get('deslocamento'),'10');
    await page.reload();await page.waitForFunction(()=>$('achados-intervalo').textContent==='11–20 de 32');
    await page.click('#achados-anterior');await page.waitForFunction(()=>$('achados-intervalo').textContent==='1–10 de 32');
    await page.goBack();await page.waitForFunction(()=>$('achados-intervalo').textContent==='11–20 de 32');
    await page.locator('.desktop-finding-filters > summary').click();
    await page.fill('#achados-texto','Não foi estabelecido');await page.click('#achados-buscar');
    await page.waitForFunction(()=>$('achados-intervalo').textContent==='1–1 de 1');
    assert.equal(new URL(page.url()).searchParams.has('deslocamento'),false);
    result.checks.push('Achados: contexto recolhido, primeira ficha visível, paginação preservada em reload/Voltar e resetada em nova pesquisa.');
    await page.click('#ver-codex');await page.selectOption('#codex-conversa',chat);
    await page.locator('.codex-answer').waitFor();
    await page.waitForFunction(()=>$('desktop-composicao').hidden);
    assert.ok((await page.locator('#codex-form').boundingBox()).height<100);
    await page.locator('.source-citation').click();
    const bounds=await page.locator('#codex-painel-fontes > summary').evaluate(el=>({top:el.getBoundingClientRect().top,header:document.querySelector('.app-header').getBoundingClientRect().bottom}));
    assert.ok(bounds.top>bounds.header,'O painel deve permanecer abaixo do cabeçalho.');
    result.sourcePane=bounds;
    await screenshot('conversa-fontes-desktop');
    await page.click('#desktop-composicao-alternar');await page.fill('#codex-pergunta','Rascunho sintético preservado.');
    await page.click('#desktop-composicao-alternar');
    assert.equal(await page.inputValue('#codex-pergunta'),'Rascunho sintético preservado.');
    assert.match(await page.locator('.desktop-composer-toolbar').innerText(),/Rascunho preservado/);
    await page.click('#desktop-composicao-alternar');
    assert.equal(await page.locator('#codex-pergunta').evaluate(el=>el===document.activeElement),true);
    result.checks.push('Conversa: composição recolhida, fonte visível após citação, rascunho preservado e foco restaurado ao expandir.');
    await page.fill('#codex-pergunta','');
    await page.click('#ver-apuracao');await page.locator('#apuracao-nova:not([disabled])').waitFor();
    await page.click('#apuracao-nova');
    await page.locator('#apuracao-vditor .vditor-wysiwyg .vditor-reset').waitFor();assert.equal(await page.locator('#apuracao-vditor .vditor-wysiwyg .vditor-reset').evaluate(el=>getComputedStyle(el).fontSize),'17px');
    assert.equal(await page.locator('#apuracao-notas').isVisible(),false);
    await page.fill('#apuracao-nota-titulo','Nota sintética');await editor.write(page,'Texto confortável para leitura.');
    await page.click('#apuracao-salvar');await page.waitForFunction(()=>$('apuracao-status').textContent.startsWith('Nota salva.'));
    await screenshot('caderno-desktop');
    result.checks.push('Editor Vditor: fonte de 17 px, primeira nota sem coluna vazia e salvamento preservado.');
    await page.click('#caderno-aba-trechos');await page.locator('#caderno-proximo:not([disabled])').waitFor();
    await page.click('#caderno-proximo');await page.waitForFunction(()=>$('caderno-intervalo').textContent==='21–22 de 22');
    await page.reload();await page.waitForFunction(()=>$('caderno-intervalo').textContent==='21–22 de 22');
    result.checks.push('Trechos com fonte preservam a segunda página após recarregar.');
    await page.selectOption('#contexto-caso','beta');await page.click('#ver-documentos');
    await page.selectOption('#rodada','R001');await page.selectOption('#geracao','v1');await page.locator('#buscar:not([disabled])').waitFor();
    await page.fill('#consulta','Consulta');await page.click('#buscar');await page.locator('#proximo:not([disabled])').waitFor();
    await page.click('#proximo');await page.waitForFunction(()=>location.search.includes('deslocamento=10'));
    await page.reload();await page.waitForFunction(()=>$('intervalo').textContent.startsWith('11–'));
    result.checks.push('Pesquisa documental preserva a segunda página após recarregar.');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('#ver-codex').evaluate(el=>el.tagName),'BUTTON');
    assert.equal(await page.locator('#desktop-composicao').count(),0);
    await page.click('#ver-apuracao');await page.locator('#apuracao-nova:not([disabled])').waitFor();await page.click('#apuracao-nova');
    await page.locator('#apuracao-vditor .vditor-wysiwyg .vditor-reset').waitFor();assert.equal(await page.locator('#apuracao-vditor .vditor-wysiwyg .vditor-reset').evaluate(el=>getComputedStyle(el).fontSize),'17px');
    result.checks.push('Ao reduzir a janela, retornam os botões, o formulário mobile e a tipografia legível do editor.');
    for (const width of [390,320]) {
      const pages=[];
      for (const baseline of [false,true]) {
        const mobile=await browser.newPage({viewport:{width,height:844}});
        mobile.on('pageerror',error=>result.errors.push(error.message));
        if(baseline)await mobile.route('**/desktop.js',route=>route.fulfill({body:'',contentType:'text/javascript'}));
        await mobile.goto(origin);await mobile.locator('#area-inicio').waitFor({state:'visible'});
        await mobile.selectOption('#contexto-caso','alpha');await mobile.click('#ver-codex');
        await mobile.locator('#codex-conta').filter({hasText:'Conectado'}).waitFor();
        await mobile.waitForFunction(()=>$('area-titulo').textContent==='Perguntar à IA'&&$('area-descricao').textContent==='Caso sintético alpha');
        await mobile.evaluate(()=>document.fonts.ready);await mobile.evaluate(()=>scrollTo(0,0));
        pages.push(mobile);
      }
      const screenshots=await Promise.all(pages.map(p=>p.screenshot()));
      await fs.writeFile(path.join(output,`mobile-atual-${width}.png`),screenshots[0]);
      await fs.writeFile(path.join(output,`mobile-base-${width}.png`),screenshots[1]);
      const actual=PNG.sync.read(screenshots[0]),baseline=PNG.sync.read(screenshots[1]);
      assert.equal(actual.width,baseline.width);assert.equal(actual.height,baseline.height);
      const changed=pixelmatch(actual.data,baseline.data,null,actual.width,actual.height,{threshold:0.1});
      (result.mobileComparisons ||= []).push({width,changedPixels:changed,threshold:0.1});
      assert.equal(changed,0,`Mobile de ${width}px deve preservar a aparência com e sem os aprimoramentos desktop (desconsiderando antialiasing).`);
      assert.equal(await pages[0].evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
      await fs.writeFile(path.join(output,`mobile-preservado-${width}.png`),screenshots[0]);
      for(const mobile of pages)await mobile.close();
    }
    result.checks.push('Capturas mobile em 390 e 320 px sem diferenças visuais pelo pixelmatch (threshold 0,1); sem transbordamento horizontal.');
    assert.deepEqual(result.errors,[]);
    result.ok=true;console.log(JSON.stringify(result,null,2));
  } catch(error) {result.failure=error.stack;result.cadernoRequests=requests;result.state=await page.evaluate(()=>({url:location.href,notice:$('experiencia-status').textContent,status:$('caderno-status').textContent,range:$('caderno-intervalo').textContent}));await screenshot('falha');throw error;}
  finally {await fs.writeFile(path.join(output,'resultado.json'),JSON.stringify(result,null,2));await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
